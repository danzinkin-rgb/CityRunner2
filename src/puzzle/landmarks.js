// Every monument is a list of blocks: { p:[x,y,z], s:[w,h,d], c:'#hex', shape }
// shape: 'box' (default) | 'cyl' | 'cone' | 'sphere' | 'dome' | 'torus'
// Blocks are ordered bottom-up; the puzzle requires rough bottom-up assembly.

const B = (p, s, c, shape = 'box') => ({ p, s, c, shape });

// ---------- helpers ----------
function ring(cx, y, r, n, size, c, shape = 'box') {
  const out = [];
  for (let i = 0; i < n; i++) {
    const a = (i / n) * Math.PI * 2;
    out.push({ p: [cx + Math.cos(a) * r, y, Math.sin(a) * r], s: size, c, shape, rotY: -a });
  }
  return out;
}

